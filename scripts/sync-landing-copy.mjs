#!/usr/bin/env node
// Copies the front page's text (the `landing` keys of the app's locale files)
// into backend/src/data/landingCopy.json, which the crawler-rendered front
// pages (/ and /<language> in backend/src/routes/og/site.js) are built from. The
// backend image is built from backend/ alone, so it cannot read
// frontend/src/locales itself.
//
// Run it after changing landing.* in the English locale: backend
// src/data/landingCopy.test.js fails until you do. The same run brings in the
// current translations of every front-page language.
//
//   node scripts/sync-landing-copy.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { FRONT_PAGE_LANGUAGES } = createRequire(import.meta.url)(path.join(root, 'backend/src/config/languages.js'));
const OUT = path.join(root, 'backend/src/data/landingCopy.json');

function landingOf(code) {
  const file = path.join(root, 'frontend/src/locales', code, 'translation.json');
  const { landing } = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!landing || typeof landing !== 'object') throw new Error(`${path.relative(root, file)} has no landing keys`);
  return landing;
}

const copy = {
  _source: 'Generated by scripts/sync-landing-copy.mjs from the landing keys of frontend/src/locales/<language>/translation.json. Do not edit by hand.',
};
for (const code of ['en', ...FRONT_PAGE_LANGUAGES]) copy[code] = landingOf(code);

fs.writeFileSync(OUT, `${JSON.stringify(copy, null, 2)}\n`);
console.log(`Wrote ${path.relative(root, OUT)}: ${['en', ...FRONT_PAGE_LANGUAGES].join(', ')}`);
